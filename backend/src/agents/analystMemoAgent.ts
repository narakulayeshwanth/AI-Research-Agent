import { withStructuredOutputFallback } from "../lib/llm";
import { AnalystMemoSchema, type ResearchState } from "../types/investment";

export async function analystMemoAgent(state: ResearchState): Promise<Partial<ResearchState>> {
  const { companyProfile: p, financialAnalysis: f, newsAnalysis: n, riskAnalysis: r, investmentDecision: d } = state;
  if (!p || !f || !d) throw new Error("Analyst memo requires complete analysis");

  const dateStr = new Date().toLocaleDateString("en-US", {
    year: "numeric", month: "long", day: "numeric"
  });

  const prompt = `Write a brief professional analyst memo for ${p.name} (${p.ticker}).
${p.sector} sector. Financial score ${f.overallScore}/10. Recommendation: ${d.recommendation} (${d.confidence}% confidence).
Revenue ${p.revenueFormatted}, margin ${p.profitMarginPct?.toFixed(1) ?? "N/A"}%, P/E ${p.peRatio?.toFixed(1) ?? "N/A"}x, risk ${r?.overallRiskLevel ?? "Medium"}, news ${n?.overallSentiment ?? "neutral"}.

Write each section in 1-2 short sentences:
- executiveSummary: What the company does and investment context
- investmentThesis: Core reason for the ${d.recommendation} recommendation
- financialHealth: What the financial metrics indicate
- riskAssessment: Top risks to watch
- investmentRecommendation: Final call with confidence
- conclusion: Outlook in 1 sentence
- analystNote: "Analysis generated by AI. Not financial advice."`;

  const memo = await withStructuredOutputFallback(AnalystMemoSchema, prompt, { temperature: 0.3 });

  return {
    analystMemo: {
      ...memo,
      dateGenerated: dateStr,
      sources: ["Yahoo Finance", "NewsAPI.org", "NVIDIA NIM LLM", "Formula-based Scoring Engine"],
    },
    completedAgents: [...state.completedAgents, "analystmemo"],
  };
}
